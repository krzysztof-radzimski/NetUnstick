#!/usr/bin/env python3
"""Generate and verify the app-owned localization resources; no network access."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Tools/LocalizationSource.json"
RESOURCES = ROOT / "Packages/NetUnstickKit/Sources/NetUnstickCore/Resources"
FORMAT = re.compile(r"%(?:(\d+)\$)?([-+#0 ]*\d*(?:\.\d+)?(?:hh|ll|[hlLzjt])?[@diuoxXfFeEgGaAcCsSp])")


def placeholders(value):
    stripped = value.replace("%%", "")
    matches = list(FORMAT.finditer(stripped))
    if "%" in FORMAT.sub("", stripped):
        raise ValueError("invalid printf placeholder")
    # Numbered placeholders may be reordered by translators. Non-numbered ones
    # must preserve order and type, otherwise String(format:) is unsafe.
    return Counter((int(m[1]) if m[1] else i + 1, m[2][-3:] if m[2].endswith("lld") else m[2][-1])
                   for i, m in enumerate(matches))


def encoded(value):
    return json.dumps(value, ensure_ascii=False)


def string_file(values):
    return "// Generated by Tools/Localization.py; edit LocalizationSource.json or Translations.\n" + "".join(
        f"{encoded(key)} = {encoded(value)};\n" for key, value in sorted(values.items()))


def catalog():
    source = json.loads(SOURCE.read_text())
    values = {language: {} for language in source["languages"]}
    for key, row in source["strings"].items():
        for language, value in row.items():
            if language in values:
                values[language][key] = value
    for path in sorted((ROOT / "Tools/Translations").glob("*.json")):
        for language, translations in json.loads(path.read_text()).items():
            if language not in values:
                raise ValueError(f"{path.name}: unsupported locale {language}")
            for key, value in translations.items():
                if key not in source["strings"]:
                    raise ValueError(f"{path.name}: unknown key {key}")
                if key in values[language] and values[language][key] != value:
                    raise ValueError(f"{path.name}: duplicate translation {language}/{key}")
                values[language][key] = value
    return source, values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write generated resources after validation")
    parser.add_argument("--languages", help="limit the development check; release verification must omit this")
    args = parser.parse_args()
    source, values = catalog()
    languages = args.languages.split(",") if args.languages else source["languages"]
    errors = []
    for language in languages:
        if language not in values:
            errors.append(f"unknown locale: {language}")
            continue
        missing = set(source["strings"]) - values[language].keys()
        if missing:
            errors.append(f"{language}: {len(missing)} missing keys ({', '.join(sorted(missing)[:4])})")
        for key, value in values[language].items():
            if not isinstance(value, str) or not value.strip():
                errors.append(f"{language}/{key}: empty or non-string translation")
                continue
            try:
                if placeholders(value) != placeholders(source["strings"][key]["en"]):
                    errors.append(f"{language}/{key}: placeholder types/order differ from English")
            except ValueError as error:
                errors.append(f"{language}/{key}: {error}")
    # Detect a newly introduced literal key that lacks source text. Dynamic keys
    # belong only to the closed enum mappings tested in LocalizationTests.
    for directory in [ROOT / "NetUnstick", ROOT / "Packages/NetUnstickKit/Sources"]:
        for path in directory.rglob("*.swift"):
            if "TestSupport" in path.parts:
                continue
            for match in re.finditer(r'L10n\.(?:text|format)\("([^"\\]+)"\s*[,)]', path.read_text()):
                key = match[1]
                if key not in source["strings"]:
                    errors.append(f"{path.relative_to(ROOT)}: unknown localization key {key}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    generated = {}
    for language in languages:
        generated[RESOURCES / f"{language}.lproj/Localizable.strings"] = string_file(values[language])
        generated[ROOT / f"NetUnstick/Resources/{language}.lproj/InfoPlist.strings"] = string_file({
            "NSLocalNetworkUsageDescription": values[language]["local_network_usage_description"]
        })
    index = {"languages": source["languages"], "keys": sorted(source["strings"])}
    generated[RESOURCES / "LocalizationIndex.json"] = json.dumps(index, ensure_ascii=False, indent=2) + "\n"
    stale = []
    for path, content in generated.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Generated localization resources are stale. Run Tools/Localization.py --write:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"Localization verified: {len(source['strings'])} keys × {len(languages)} languages; placeholders match.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f"Localization error: {error}", file=sys.stderr)
        sys.exit(1)
